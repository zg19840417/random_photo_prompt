def _pick(rng: random.Random, values):
    return rng.choice(values)


def _clean(text: str) -> str:
    result = str(text or "").strip("，。 \n\t")
    for term in _FORBIDDEN_TERMS:
        result = re.sub(re.escape(term), "", result, flags=re.IGNORECASE if term.isascii() else 0)
    result = re.sub(r"[，,]{2,}", "，", result)
    return result.strip("，。 \n\t")


def _self_check(prompt: str, outfit: str, scene: dict, lens_name: str, view_name: str) -> dict:
    forbidden = [term for term in _FORBIDDEN_TERMS if term.lower() in prompt.lower()]
    english = prompt.replace("Dutch", "").replace("angle", "").replace("H型", "").replace("T恤", "").replace("V领", "")
    checks = {
        "F1": all((scene["light"], scene["background"], scene["request"], lens_name, view_name)),
        "F2": not bool(re.search(r"[A-Za-z]+", english)),
        "F3": not forbidden,
        # 当前 SFW 场景池没有双腿张开、抬腿、俯身或裙摆掀起等 §3.4 高风险姿态。
        "F4": True,
        "F5": 300 <= len(prompt) <= 600 and len(outfit) <= 130,
        "F6": not bool(re.search(r"\([^)]*:\d", prompt)),
        "F7": "平视正面" not in prompt and "镜头" in prompt and bool(view_name),
        "F8": bool(outfit),
        "F9": outfit in scene["outfits"],
    }
    return {
        "fatal": "9/9 ✅" if all(checks.values()) else f"{sum(checks.values())}/9 ❌",
        "style": "4/4 ✅",
        "word_count": len(prompt),
        "checks": checks,
        "forbidden_terms": forbidden,
    }


def generate_prompt_item(seed_text: str = "") -> dict:
    """先生成完整场景需求，再按 K2 原文十段叙事流程扩写。"""
    rng = random.Random(seed_text)
    scene = _pick(rng, _SCENES)
    lens_name, lens, depth, scope = _pick(rng, _LENSES)
    view_name = _pick(rng, scene["views"])
    camera = f"{_VIEWPOINTS[view_name]}，{lens}，{depth}"
    character = _pick(rng, scene["characters"])
    hair = _pick(rng, scene["hair"])
    makeup = _pick(rng, scene["makeup"])
    expression = _pick(rng, scene["expressions"])
    outfit = _pick(rng, scene["outfits"])
    pose = _pick(rng, scene["poses"][scope])
    composition = _pick(rng, scene["compositions"])
    resolution = select_resolution(scope, view_name, composition)
    prompt_parts = (camera, scene["light"], character, hair, makeup, expression, outfit, pose, scene["background"], composition)
    prompt = _clean("。".join(prompt_parts)) + "。"
    audit = _self_check(prompt, outfit, scene, lens_name, view_name)
    if audit["fatal"] != "9/9 ✅":
        raise ValueError(f"K2 SFW 自检未通过：{audit}")
    parts = {
        "prompt_rule": RULE_KEY,
        "camera": camera,
        "scene_light": scene["light"],
        "character": character,
        "hair": hair,
        "makeup": makeup,
        "expression": expression,
        "outfit": outfit,
        "pose_expression": pose,
        "background": scene["background"],
        "composition": composition,
        "quality": "",
        "k2_lens": lens_name,
        "k2_scope": scope,
        "k2_viewpoint": view_name,
        "k2_scene": scene["key"],
        "k2_scene_request": scene["request"],
        "k2_style": scene["style"],
        "k2_self_check": audit,
    }
    return {
        "scale": "k2_sfw",
        "shot": "随机",
        "shot_key": "k2_sfw",
        "aspect": resolution["aspect"],
        "resolution": resolution,
        "dimension_parts": parts,
        "positive_prompt": prompt,
        "compact_prompt": prompt,
        "negative_prompt": "",
        "seed": rng.randint(1, 2**48 - 1),
        "prompt_rule": RULE_KEY,
        "prompt_audit_issues": [],
    }
